"""
案例:
    演示RNN层(循环网络层)的API。
循环网络层作用:
    基于 上一次的隐藏状态 + 本次的输入 → 本次的隐藏状态, 本次的输出。
公式:
    本次的隐藏状态 = tanh(上次的隐藏状态加权求和 + 本次的输入 加权求和)
    本次的输出 = 本次的隐藏状态加权求和, 有词汇表中所有词的概率, 选概率最大的哪个词作为 最终预测结果。
简单总结下RNN:
    词嵌入层:
        将词(词的索引) 转换为 词向量表示。
    RNN层(循环网络层):
        逐步处理词向量, 生成 每个时间步的 隐藏状态。
    全连接层(输出映射):
        通过线性变换将隐藏状态映射到输出, 通常是1个词汇表中词的概率分布。
"""
import torch
import torch.nn as nn

# 1. 定义一个RNN层
# 参1:input_size词向量的维度，就像电影里每一帧画面有128个细节(比如: 颜色，动作，表情等)，RNN(你的大脑)每次看到的就是这128个细节。
# 参2:hidden_size隐藏状态向量维度，你的大脑能记住的剧情信息量有多大，比如说: 记住角色关系，前景提要，值越大，能存储的剧情信息越多。
# 参3:num_layers隐藏层数量，默认是1，你的大脑只有1层来处理它，如果是2，说明2层大脑接力理解剧情，第1层处理，第2层加工。
rnn = nn.RNN(input_size=128, hidden_size=256, num_layers=1)

# 2. 定义变量，表示输入的 x
# 参1: 每个句子的词的个数(长度)，假设电影总共有 5帧画面。
# 参2: 句子的数量(batch_size)，同时有32个人在看这 5帧画面。
# 参3: 词向量的维度。每一帧画面的细节是128个。
input = torch.randn(5, 32, 128)

# 3. 初始化隐藏状态h0
# 参1: 隐藏层数量num_layers，默认是1，你的大脑只有1层来处理它，如果是2，说明2层大脑接力理解剧情，第1层处理，第2层加工。
# 参2: batch句子的数量，同时有32个人在看这 5帧画面。
# 参3: hidden_size隐藏状态向量维度，你的大脑能记住的剧情信息量有多大，比如说: 记住角色关系，前景提要，值越大，能存储的剧情信息越多。
h0 = torch.randn(1, 32, 256)

# 4. 将输入和隐藏状态传入RNN层
# 参1: 输入的 x
# 参2: 初始化的隐藏状态
# 返回值:
# output: 每个时间步的隐藏状态, 形状为: [seq_len, batch, hidden_size]
# hn: 最后一个时间步的隐藏状态, 形状为: [num_layers, batch, hidden_size]
output, hn = rnn(input, h0)
print(output.shape)  # torch.Size([5, 32, 256])
print(hn.shape)      # torch.Size([1, 32, 256])
