"""
案例:
    演示 张量的 索引操作。

分类:
    简单行列索引
    列表索引
    范围索引
    布尔索引
    多维索引

掌握:
    简单行列索引，范围索引，多维索引。
"""

# 导包
import torch

#1.设置随机种子
torch.manual_seed(24)

def dm01():
    """
    演示PyTorch张量的索引操作
    包括简单行列索引、列表索引、范围索引、布尔索引以及多维索引
    """
    #2.创建随机张量
    t1 = torch.randint(1, 10, (5, 5))  # 创建一个5x5的随机整数张量，值在1到10之间
    print(f't1:{t1}')  # 打印张量t1的内容
    print('-' * 30)  # 打印分隔线，用于区分不同的输出部分

    #3.演示张量的索引操作
    #场景1：简单行列索引
    #需求1：获取第2行的元素
    print(t1[1])  # 使用简单索引获取第2行（索引从0开始）的所有元素
    print(t1[1, :])     #效果同上，这里的冒号表示获取所有列

    #需求2：获取所有行的第3列的元素
    print(t1[:, 2])      #获取所有行的第3列的元素
    print('-' * 30)

    #场景2：列表索引
    #需求1：返回（0， 1），（1， 2）的元素
    print(t1[[0, 1], [1, 2]])

    #需求2：返回（1，2）（3，4）的元素
    print(t1[[1, 3, 4], [2, 4, 3]])

    #需求3：获取0，1行的1，2列的4个元素
    # print(t1[[[0],[1]], [1, 2]])
    print(t1[0:2, 1:3])
    print('-' * 30)

    #场景3：范围索引
    #需求1：获取前3行，前2行的元素
    print(t1[:3, :2])

    #需求2：获取第2行到最后一行，前2列的元素
    print(t1[1:, :2])

    #需求3：所有奇数行，所有偶数列的元素
    print(t1[[[1],[3]], [0,2,4]])
    print(t1[1::2, ::2])

    print('-' * 30)
    #场景4：布尔索引
    # print(t1[torch.tensor([True, False, False, True, True]), :])

    #需求1：获取第3列大于5的行数据
    print(t1[t1[:, 2] > 5])
    print('-' * 30)

    #需求2：获取第2行，大于5的列数据
    #理解1：在第2行基础上，找到该行中大于5的列索引，然后找到所有行对应的列元素
    # print(t1[:, t1[1, :] > 5])
    print(t1[:, t1[1] > 5])     #效果同上

    #理解2：在第2行基础上，，找到该行所有列中大于5的元素
    print(t1[1, t1[1, :] > 5])

    print('-' * 30)

    #场景5：多维索引
    #创建3维张量, 2个3行4列的矩阵
    t2 = torch.randint(1, 10, (2, 3, 4))
    print(f't2:{t2}')

    #需求1：获取0轴上的第1个数据
    print(t2[0, :, :])

    #需求2：获取1轴上的第1个数据
    print(t2[:, 0, :])

    #需求3：获取2轴上的第1个数据
    print(t2[:, :, 0])
    print('-' * 30)

if __name__ == '__main__':
    dm01()
